function main(): void {
  if (!fs.existsSync(schemaPath)) {
    console.error("missing schema:", schemaPath);
    process.exit(1);
  }
  JSON.parse(fs.readFileSync(schemaPath, "utf8"));
  generateGoEnv();
  generatePythonConfig();
  generateInstallSnippets();
  console.log("codegen: ok");
}

main();
